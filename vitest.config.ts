import { defineConfig } from "vitest/config";

// I-145 — 这个仓库的测试套件默认会吃满机器：并发上限是「处理器核数减一」，在这台
// 24 核开发机上就是 23 个 worker，而五十六个测试文件里有十六个自己还要再启动真正的
// node 子进程去跑引擎，那些孙子进程不受上限管辖。实测一次完整跑的真实峰值是约 50 个
// 可归因进程、373 个线程、2225 MB 常驻内存。Claude、Codex、Cursor 三个助手各跑一次，
// 开发机就卡死到没法操作。
//
// 两个数字合起来才有用，缺一个都不成立：
//   maxWorkers  压住同时跑的测试文件数；
//   testTimeout 五秒的默认值撑不住那十六个文件在 Windows 上启动 npx tsx，
//               不抬它，套件在机器有负载时就是红的，「限了并发还绿着」根本无从断言。
//
// 边界，别指望它做到做不到的事：这个上限不跨会话组合。三个助手各自受限，总量仍然是
// 三份预算。要让多个会话共享同一份名额，需要跨会话租约，那是另一个想法。
// 孙子进程同样在预算之外 —— 唯一能同时管住两者的机制是 jobserver 协议，node 的测试
// 生态一个实现都没有。

// 6 不是拍的，是按测试运行器官方 doctor 命令的办法测出来的：从默认值的一半开始减半，
// 只有比当前最好成绩快百分之五以上才继续往下减。2026-09-15 在这台 24 核机器上实测，
// 每档整套 57 个文件 614 条测试全绿 ——
//   12 档 20.35s ／ 6 档 18.18s（快 10.7%，过阈值，继续减）／ 3 档 28.95s（反而变慢，停）
// 标准的 U 形曲线，拐点就在 6：再往上加 worker 买不到速度，只买到机器占用。
// 换机器或者套件长大之后这个数会漂，重测一遍就是了。
//
// 逃生口：临时想放开或收紧，设环境变量 VITEST_MAX_WORKERS，不用改这个文件。
// 只写整数 —— 那条路径是用 parseInt 解析的，写 "50%" 会变成 50 个 worker。
const MAX_WORKERS = Number.parseInt(process.env.VITEST_MAX_WORKERS ?? "", 10) || 6;

export default defineConfig({
  test: {
    maxWorkers: MAX_WORKERS,
    testTimeout: 30_000,
    hookTimeout: 30_000,
  },
});
